-- Create Kakheti Heritage table for storing diverse information about Kakheti
CREATE TABLE IF NOT EXISTS public.kakheti_heritage (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  category text CHECK (category IN ('ისტორია', 'ბუნება', 'ღვინო', 'პერსონაჟი', 'ლეგენდა', 'კულტურა', 'არქიტექტურა', 'ტრადიცია')),
  title text NOT NULL,
  description text,
  fun_fact text, -- Short, entertaining fact "Did you know?"
  image_url text,
  location_name text,
  is_published boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Enable Row Level Security
ALTER TABLE public.kakheti_heritage ENABLE ROW LEVEL SECURITY;

-- Create policy for public read access
CREATE POLICY "Kakheti heritage is publicly readable" ON public.kakheti_heritage
FOR SELECT USING (is_published = true);

